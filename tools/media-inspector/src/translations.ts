export function createTranslator(language: Language): (key: string, replacements?: Record<string, string | number>) => string {
  return (key, replacements = {}) => {
    let value = translations[language][key] ?? translations.en[key] ?? key;
    for (const [name, replacement] of Object.entries(replacements)) value = value.replaceAll(`{${name}}`, String(replacement));
    return value;
  };
}
